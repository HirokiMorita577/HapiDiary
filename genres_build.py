def build():
    genres = []
    gid = 0
    for major, genre_name, subs in DATA:
        gid += 1
        assert major in MAJOR_CATEGORIES, major
        assert 4 <= len(subs) <= 8, (genre_name, len(subs))
        assert len({s[0] for s in subs}) == len(subs), ("dup subgenre in", genre_name)
        subgenres = []
        for (name, desc, example, sensitive, mute_theme, keywords) in subs:
            subgenres.append({
                "name": name,
                "description": desc,
                "example": example,
                "sensitive": bool(sensitive),
                "mute_theme": mute_theme,
                "keywords": keywords,
            })
        genres.append({
            "id": gid,
            "major": major,
            "name": genre_name,
            "subgenres": subgenres,
        })
    assert len(genres) == 30, len(genres)
    total_subs = sum(len(g["subgenres"]) for g in genres)
    out = {
        "major_categories": MAJOR_CATEGORIES,
        "mute_themes": MUTE_THEMES,
        "genres": genres,
    }
    here = os.path.dirname(os.path.abspath(__file__))
    dest = os.path.join(here, "genres.json")
    with open(dest, "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=2)
    print("wrote", dest, "genres=", len(genres), "subgenres=", total_subs)


if __name__ == "__main__":
    build()
